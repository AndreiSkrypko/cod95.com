export function isServiceId(value: string): value is ServiceId {
  return SERVICES.some((s) => s.id === value);
}

export function getServiceById(id: ServiceId): LandingService | undefined {
  return SERVICES.find((s) => s.id === id);
}

export function getServicePageDetail(service: LandingService): ServicePageDetail {
  const extra = DETAILS[service.id];
  const base: ServicePageDetail = {
    lead: extra?.lead ?? service.text,
    sections: extra?.sections ?? [
      {
        title: "Описание",
        paragraphs: [service.text],
      },
    ],
  };
  if (extra?.steps) base.steps = extra.steps;
  if (extra?.checklist) base.checklist = extra.checklist;
  return base;
}
